import streamlit as st

st.set_page_config(
    page_title="Data Analysis Agent",
    page_icon="📊",
    layout="wide",
    initial_sidebar_state="expanded",
)

ROOT = Path(__file__).parent
sys.path.insert(0, str(ROOT / "src"))

try:
    from agent.agent import ask
    from agent.tools import FIGURES
    AGENT_READY, AGENT_IMPORT_ERROR = True, None
except Exception as exc:  # missing key, missing package, ...
    AGENT_READY, AGENT_IMPORT_ERROR = False, exc

LOG_PATH = ROOT / "logs" / "agent.jsonl"
MAX_UPLOAD_MB = 25
STEP_LIMIT_TEXT = "Stopped: hit step limit."
FRIENDLY_ERROR = (
    "I couldn't answer that reliably. Try rephrasing the question "
    "or asking something narrower."
)
TRUST_NOTE = "Answers are generated by AI from your data. Check important numbers."


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
@st.cache_data(show_spinner=False)
def _parse_csv(raw: bytes) -> pd.DataFrame:
    return pd.read_csv(io.BytesIO(raw))


def load_csv(raw: bytes) -> pd.DataFrame:
    # The agent's generated code can mutate df (e.g. parsing dates), so never
    # hand out the cached object itself.
    return _parse_csv(raw).copy()


def data_summary(df: pd.DataFrame) -> pd.DataFrame:
    return pd.DataFrame(
        {
            "column": df.columns.astype(str),
            "type": [str(t) for t in df.dtypes],
            "missing": df.isna().sum().to_numpy(),
        }
    )


def _looks_like_date(series: pd.Series) -> bool:
    if pd.api.types.is_datetime64_any_dtype(series):
        return True
    name = str(series.name).lower()
    return not pd.api.types.is_numeric_dtype(series) and any(
        key in name for key in ("date", "time", "month", "year", "day")
    )


def _pick_metric(numeric_cols: list[str]) -> str:
    for key in ("revenue", "sales", "amount", "total", "price", "value", "cost"):
        for col in numeric_cols:
            if key in col.lower():
                return col
    return numeric_cols[-1]


def _is_identifier(df: pd.DataFrame, col: str) -> bool:
    """IDs, codes and free-text keys make poor grouping columns."""
    name = str(col).lower()
    if name in {"id", "index", "uuid"} or name.endswith(("_id", "id", "_no", "code")):
        return True
    return df[col].nunique(dropna=True) == len(df) > 20


def suggest_questions(df: pd.DataFrame) -> list[str]:
    """Starter questions derived from the uploaded columns."""
    numeric, categorical, temporal = [], [], []
    for col in df.columns:
        series = df[col]
        if pd.api.types.is_numeric_dtype(series):
            numeric.append(col)
        elif _looks_like_date(series):
            temporal.append(col)
        elif not _is_identifier(df, col):
            categorical.append(col)

    # Prefer business-like dimensions (in priority order), then fewest distinct values.
    preferred = ("product", "item", "category", "region", "segment", "customer", "name", "type")

    def rank(col: str) -> tuple[int, int]:
        name = str(col).lower()
        for index, key in enumerate(preferred):
            if key in name:
                return (index, df[col].nunique(dropna=True))
        return (len(preferred), df[col].nunique(dropna=True))

    categorical.sort(key=rank)

    questions: list[str] = []
    if categorical and numeric:
        metric = _pick_metric(numeric)
        questions.append(f"Which {categorical[0]} has the lowest {metric}?")
        questions.append(f"Which {categorical[0]} has the highest {metric}?")
    if temporal and numeric:
        questions.append(f"Is there a trend in {_pick_metric(numeric)} over time?")
    if numeric:
        questions.append(f"Are there outliers in {_pick_metric(numeric)}?")
    questions.append("Are there missing values I should worry about?")
    return questions[:4]


def _log_size() -> int:
    try:
        return LOG_PATH.stat().st_size
    except OSError:
        return 0


def _read_new_trace(offset: int) -> dict | None:
    """The agent logs one JSON line per completed question; read what was appended."""
    try:
        with LOG_PATH.open("rb") as handle:
            handle.seek(offset)
            chunk = handle.read().decode("utf-8", "ignore")
    except OSError:
        return None
    for line in reversed(chunk.splitlines()):
        line = line.strip()
        if not line:
            continue
        try:
            return json.loads(line)
        except json.JSONDecodeError:
            continue
    return None


def run_agent(question: str, df: pd.DataFrame, history):
    """Call the existing agent, returning its answer plus the trace and charts."""
    offset = _log_size()
    figures_before = len(FIGURES)

    # Work on a copy so a failed call cannot leave a dangling user message in history.
    working = list(history) if history else None

    error: str | None = None
    try:
        answer, new_history = ask(question, df, working)
    except Exception as exc:  # network, auth, rate limit...
        answer, new_history, error = None, history, f"{type(exc).__name__}: {exc}"

    trace = _read_new_trace(offset) or {}
    steps = trace.get("steps", [])
    figures = FIGURES[figures_before:]
    return answer, new_history, steps, figures, error, trace.get("tokens")


def chart_png(fig) -> bytes | None:
    try:
        return fig.to_image(format="png", scale=2)
    except Exception:
        return None


def conversation_markdown() -> str:
    lines = ["# Data Analysis Agent - conversation", ""]
    for entry in st.session_state.chat:
        if entry["role"] == "user":
            lines += ["## You", "", entry["content"], ""]
            continue
        lines += ["## Agent", "", entry["answer"], ""]
        for step in entry.get("steps", []):
            lines += ["```python", step.get("code", ""), "```", ""]
            result = (step.get("result") or "").strip()
            if result:
                lines += ["```text", result[:2000], "```", ""]
    return "\n".join(lines)


def _next_id() -> int:
    st.session_state.entry_seq += 1
    return st.session_state.entry_seq


def render_assistant(entry: dict, show_code: bool) -> None:
    st.markdown(entry["answer"])

    if "png" not in entry:
        entry["png"] = [chart_png(fig) for fig in entry.get("figures", [])]

    for index, fig in enumerate(entry.get("figures", [])):
        st.plotly_chart(fig, width="stretch", key=f"chart-{entry['id']}-{index}")
        png = entry["png"][index] if index < len(entry["png"]) else None
        if png:
            st.download_button(
                "Download chart as PNG",
                png,
                file_name=f"chart-{index + 1}.png",
                mime="image/png",
                key=f"png-{entry['id']}-{index}",
            )
        else:
            st.download_button(
                "Download chart (.html)",
                fig.to_html(include_plotlyjs="cdn"),
                file_name=f"chart-{index + 1}.html",
                mime="text/html",
                key=f"html-{entry['id']}-{index}",
            )

    steps = entry.get("steps") or []
    if not steps and not entry.get("error"):
        return

    with st.expander("How I got this", expanded=show_code):
        if entry.get("error"):
            st.caption("The agent raised an error on this question:")
            st.code(entry["error"], language="text")
        for step in steps:
            flags = "error" if step.get("error") else "ok"
            st.caption(f"{step.get('latency_s', '?')}s · {flags}")
            st.code(step.get("code", ""), language="python")
            result = (step.get("result") or "").strip()
            if result:
                st.text(result[:2000])


# --------------------------------------------------------------------------- #
# Session state
# --------------------------------------------------------------------------- #
st.session_state.setdefault("chat", [])
st.session_state.setdefault("history", None)
st.session_state.setdefault("df", None)
st.session_state.setdefault("file_id", None)
st.session_state.setdefault("entry_seq", 0)
st.session_state.setdefault("pending_question", None)
st.session_state.setdefault("show_code", False)

df: pd.DataFrame | None = st.session_state.df


# --------------------------------------------------------------------------- #
# Sidebar
# --------------------------------------------------------------------------- #
with st.sidebar:
    st.title("📊 Data Analysis Agent")
    st.caption("Upload a CSV, ask questions in plain English, get answers and charts.")

    if not AGENT_READY:
        st.error(
            "The agent could not start. Check that GROQ_API_KEY is set in `.env` "
            "and that dependencies are installed."
        )
        with st.expander("Details"):
            st.code(f"{type(AGENT_IMPORT_ERROR).__name__}: {AGENT_IMPORT_ERROR}")
        st.stop()

    uploaded = st.file_uploader("Upload a CSV", type=["csv"])

    if uploaded is not None:
        file_id = (uploaded.name, uploaded.size)
        if st.session_state.file_id != file_id:
            try:
                st.session_state.df = load_csv(uploaded.getvalue())
                st.session_state.file_id = file_id
                st.session_state.chat = []
                st.session_state.history = None
                df = st.session_state.df
            except Exception as exc:
                st.error(f"Could not read that CSV: {exc}")
                st.session_state.df = None
                df = None

        if uploaded.size > MAX_UPLOAD_MB * 1024 * 1024:
            st.warning(
                f"That file is {uploaded.size / 1e6:.0f} MB. Only a summary and a "
                "few sample rows are sent to the model, but large files may be slow."
            )

    if df is not None:
        st.subheader("Data preview")
        rows, cols = df.shape
        left, right = st.columns(2)
        left.metric("Rows", f"{rows:,}")
        right.metric("Columns", cols)
        st.dataframe(
            data_summary(df),
            hide_index=True,
            width="stretch",
            height=min(260, 40 + 35 * len(df.columns)),
        )

        st.subheader("Try asking")
        for question in suggest_questions(df):
            if st.button(question, width="stretch", key=f"starter-{question}"):
                st.session_state.pending_question = question
                st.rerun()

        st.divider()

    st.toggle(
        "Show the code the agent wrote",
        key="show_code",
        help="Expands the 'How I got this' section under every answer.",
    )

    if st.button("Clear conversation", width="stretch", disabled=not st.session_state.chat):
        st.session_state.chat = []
        st.session_state.history = None
        st.session_state.pending_question = None
        st.rerun()

    if st.session_state.chat:
        st.download_button(
            "Download conversation (.md)",
            conversation_markdown(),
            file_name="data-analysis-conversation.md",
            mime="text/markdown",
            width="stretch",
        )

    st.caption(TRUST_NOTE)


# --------------------------------------------------------------------------- #
# Main area
# --------------------------------------------------------------------------- #
st.subheader("Conversation")

if df is None:
    st.info("Upload a CSV in the sidebar to get started.")
else:
    st.caption(
        f"Working with **{df.shape[0]:,} rows × {df.shape[1]} columns**. "
        "The model only receives a summary and three sample rows."
    )

for entry in st.session_state.chat:
    if entry["role"] == "user":
        with st.chat_message("user"):
            st.markdown(entry["content"])
    else:
        with st.chat_message("assistant"):
            render_assistant(entry, st.session_state.show_code)

prompt = st.chat_input(
    "Ask a question about your data...",
    disabled=df is None or not AGENT_READY,
)

if not prompt:
    prompt = st.session_state.pending_question
    st.session_state.pending_question = None

if prompt and df is not None:
    st.session_state.chat.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    with st.chat_message("assistant"):
        with st.status("Analysing your data...", expanded=False) as status:
            status.update(label="Writing and running code...")
            answer, new_history, steps, figures, error, tokens = run_agent(
                prompt, df, st.session_state.history
            )

            if error:
                status.update(label="Something went wrong", state="error")
            elif any(step.get("error") for step in steps):
                status.update(label="Recovered from an error", state="complete")
            elif figures:
                status.update(label="Preparing chart...", state="complete")
            else:
                status.update(label="Done", state="complete")

        if error:
            text = FRIENDLY_ERROR
        elif not answer or answer.strip() == STEP_LIMIT_TEXT:
            text = FRIENDLY_ERROR
        else:
            text = answer
            st.session_state.history = new_history

        entry = {
            "role": "assistant",
            "id": _next_id(),
            "answer": text,
            "steps": steps,
            "figures": figures,
            "error": error,
            "tokens": tokens,
        }
        st.session_state.chat.append(entry)
        render_assistant(entry, st.session_state.show_code)
