        with st.chat_message("user"):
            st.markdown(prompt)

        with st.chat_message("assistant"):
            with st.status("Analysing your data...", expanded=False) as status:
                status.update(label="Writing and running code...")
                answer, new_history, steps, figures, error, tokens = run_agent(
                    prompt, df, st.session_state.history
                )

                if error:
                    status.update(label="Something went wrong", state="error")
                elif any(step.get("error") for step in steps):
                    status.update(label="Recovered from an error", state="complete")
                elif figures:
                    status.update(label="Preparing chart...", state="complete")
                else:
                    status.update(label="Done", state="complete")

            if error:
                text = FRIENDLY_ERROR
            elif not answer or answer.strip() == STEP_LIMIT_TEXT:
                text = FRIENDLY_ERROR
            else:
                text = answer
                st.session_state.history = new_history

            entry = {
                "role": "assistant",
                "id": _next_id(),
                "answer": text,
                "steps": steps,
                "figures": figures,
                "error": error,
                "tokens": tokens,
            }
            st.session_state.chat.append(entry)
            render_assistant(entry, st.session_state.show_code)

