def _is_date_series(df: pd.DataFrame, column: str) -> bool:
    return dash_profile.looks_like_date(df[column])


def dashboard_filters(spec: dict, df: pd.DataFrame) -> dict:
    """Sidebar filters. Purely local: changing them never calls the model."""
    values: dict = {}
    with st.sidebar:
        st.divider()
        st.subheader("Dashboard filters")
        for column in spec.get("filters", [])[:3]:
            if column not in df.columns:
                continue
            label = dash_profile.pretty_label(column)
            if _is_date_series(df, column):
                parsed = pd.to_datetime(df[column], errors="coerce").dropna()
                if parsed.empty:
                    continue
                low, high = parsed.min().date(), parsed.max().date()
                picked = st.date_input(
                    label, value=(low, high), min_value=low, max_value=high, key=f"flt-{column}"
                )
                if isinstance(picked, tuple) and len(picked) == 2:
                    values[column] = picked
            else:
                options = sorted(df[column].dropna().astype(str).unique())
                picked = st.multiselect(label, options, key=f"flt-{column}")
                if picked:
                    values[column] = picked
        if values:
            st.caption("Filters apply locally and do not use API credits.")
    return values


def apply_overrides(spec: dict, overrides: dict) -> dict:
    charts = []
    for index, chart in enumerate(spec.get("charts", [])):
        override = overrides.get(index)
        if override and not override.get("keep", True):
            continue
        chart = dict(chart)
        if override and override.get("type"):
            chart["type"] = override["type"]
        charts.append(chart)
    return {**spec, "charts": charts}


def data_quality(df: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    missing = df.isna().sum()
    missing = missing[missing > 0].sort_values(ascending=False)
    missing_table = pd.DataFrame(
        {"column": missing.index.astype(str), "missing": missing.to_numpy()}
    )

    rows = []
    for column in df.columns:
        series = df[column]
        if not pd.api.types.is_numeric_dtype(series):
            continue
        clean = series.dropna()
        if len(clean) < 10:
            continue
        q1, q3 = clean.quantile([0.25, 0.75])
        iqr = q3 - q1
        if iqr == 0:
            continue
        count = int(((clean < q1 - 1.5 * iqr) | (clean > q3 + 1.5 * iqr)).sum())
        if count:
            rows.append({"column": str(column), "outliers (IQR)": count})
    return missing_table, pd.DataFrame(rows)


def _render_chart(item: dict, key: str) -> None:
    chart = item["chart"]
    st.markdown(f"**{chart.get('title', 'Chart')}**")
    if item.get("figure") is not None:
        st.plotly_chart(item["figure"], width="stretch", key=key)
    elif item.get("table") is not None:
        st.dataframe(item["table"], width="stretch", hide_index=True)
    if item.get("insight"):
        st.caption(item["insight"])
    if item.get("error"):
        st.caption(f"Skipped: {item['error']}")


def _build_export_files(spec, filtered, rendered, kpis) -> tuple[dict, dict]:
    """Build every export in memory. Returns (files, reasons)."""
    files: dict[str, tuple[bytes, str, str]] = {}
    reasons: dict[str, str] = {}
    available = dash_export.availability()

    def attempt(key, builder, filename, mime):
        if not available.get(key, (False, ""))[0]:
            reasons[key] = available.get(key, (False, "Unavailable."))[1]
            return
        try:
            payload = builder()
            if payload:
                files[key] = (payload, filename, mime)
            else:
                reasons[key] = "Nothing to export."
        except Exception as exc:
            reasons[key] = f"{type(exc).__name__}: {exc}"

    attempt("json", lambda: dash_export.to_json(spec), "dashboard.json", "application/json")
    attempt("csv", lambda: dash_export.to_csv_zip(filtered, rendered), "dashboard-data.zip", "application/zip")
    attempt(
        "excel",
        lambda: dash_export.to_excel(filtered, rendered, kpis, spec),
        "dashboard.xlsx",
        "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
    )
    attempt("html", lambda: dash_export.to_html(spec, rendered, kpis), "dashboard.html", "text/html")

    pngs: list[bytes] = []
    if available["png"][0]:
        for item in rendered:
            if item.get("figure") is not None:
                png = dash_export.chart_png(item["figure"])
                if png:
                    pngs.append(png)

        def png_zip():
            if not pngs:
                return None
            buffer = io.BytesIO()
            with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
                for index, png in enumerate(pngs, start=1):
                    archive.writestr(f"chart-{index}.png", png)
                full = dash_export.dashboard_png(pngs)
                if full:
                    archive.writestr("dashboard.png", full)
            return buffer.getvalue()

        attempt("png", png_zip, "dashboard-charts.zip", "application/zip")
        attempt(
            "pdf",
            lambda: dash_export.to_pdf(spec, kpis, pngs),
            "dashboard.pdf",
            "application/pdf",
        )
    else:
        reasons["png"] = available["png"][1]
        reasons["pdf"] = available["pdf"][1]

    attempt("hyper", lambda: dash_export.to_hyper(filtered), "dashboard.hyper", "application/octet-stream")
    return files, reasons


def render_dashboard_tab(df: pd.DataFrame | None) -> None:
    st.caption(TRUST_NOTE)
    if df is None:
        st.info("Upload a CSV to build a dashboard")
        return

    state = st.session_state.dashboard
    focus = st.text_input(
        "Focus on... (optional)",
        value=st.session_state.dashboard_focus,
        placeholder="e.g. regional performance",
        key="dashboard_focus_input",
    )

    label = "Regenerate" if state else "Generate dashboard"
    if st.button(label, type="primary"):
        st.session_state.dashboard_focus = focus
        with st.status("Profiling data...", expanded=True) as status:
            profile = dash_profile.profile_dataframe(df)
            status.update(label="Planning dashboard...")
            try:
                spec, meta = dash_planner.plan_dashboard(profile, focus)
            except Exception as exc:
                spec = dash_planner.fallback_spec(profile)
                meta = {
                    "fallback": True,
                    "dropped": [],
                    "tokens": 0,
                    "error": f"{type(exc).__name__}: {exc}",
                }
            status.update(label="Building charts...")
            st.session_state.dashboard = {
                "spec": spec,
                "meta": meta,
                "profile": profile,
                "overrides": {},
            }
            st.session_state.export_files = {}
            status.update(label="Dashboard ready", state="complete")
        st.rerun()

    if not state:
        st.info("Click **Generate dashboard** to build one from your data.")
        return

    spec = apply_overrides(state["spec"], state["overrides"])
    clean, dropped = dash_planner.validate_spec(spec, state["profile"])
    spec = clean or state["spec"]

    filters = dashboard_filters(spec, df)
    filtered = dash_render.apply_filters(df, filters)

    st.divider()
    st.markdown(f"### {spec['title']}")
    st.caption(spec["subtitle"])

    profile = state["profile"]
    span = profile.get("date_range")
    freshness = f"{len(filtered):,} of {profile['rows']:,} rows"
    if span:
        freshness += f" · {span['min']} to {span['max']}"
    st.caption(freshness)

    if filtered.empty:
        st.warning("No rows match the current filters.")
        return

    rendered = dash_render.build_dashboard(spec, filtered)
    kpis = rendered["kpis"]
    charts = rendered["charts"]

    if dropped:
        st.caption(f"Skipped {len(dropped)} chart(s) that did not fit the data.")
    if state["meta"].get("fallback"):
        st.caption("The planner returned an unusable spec, so this is the rule-based default dashboard.")

    if kpis:
        columns = st.columns(len(kpis))
        for column, card in zip(columns, kpis):
            delta = f"{card['delta']:+.1f}% vs prev." if card.get("delta") is not None else None
            column.metric(card["label"], card["value"], delta=delta)

    if charts:
        _render_chart(charts[0], key="dash-main")
        grid = charts[1:]
        for index in range(0, len(grid), 2):
            left, right = st.columns(2)
            with left:
                _render_chart(grid[index], key=f"dash-{index}")
            if index + 1 < len(grid):
                with right:
                    _render_chart(grid[index + 1], key=f"dash-{index + 1}")

    missing_table, outliers = data_quality(filtered)
    with st.expander("Data quality", expanded=False):
        if missing_table.empty:
            st.caption("No missing values in the filtered data.")
        else:
            st.caption("Missing values per column")
            st.dataframe(missing_table, width="stretch", hide_index=True)
        if outliers.empty:
            st.caption("No outliers detected (1.5 × IQR rule).")
        else:
            st.caption("Detected outliers (1.5 × IQR rule)")
            st.dataframe(outliers, width="stretch", hide_index=True)

    with st.expander("Customize", expanded=False):
        overrides = {}
        for index, chart in enumerate(state["spec"].get("charts", [])):
            left, right = st.columns([3, 2])
            keep = left.checkbox(
                chart.get("title", f"Chart {index + 1}"),
                value=state["overrides"].get(index, {}).get("keep", True),
                key=f"keep-{index}",
            )
            current = state["overrides"].get(index, {}).get("type", chart["type"])
            options = [chart["type"]] + [t for t in dash_planner.ALLOWED_TYPES if t != chart["type"]]
            new_type = right.selectbox(
                "Type", options, index=options.index(current), key=f"type-{index}",
                label_visibility="collapsed",
            )
            overrides[index] = {"keep": keep, "type": new_type}
        if st.button("Apply changes"):
            state["overrides"] = overrides
            st.rerun()

    with st.expander("Export", expanded=False):
        st.caption(dash_export.to_tableau_notes())
        available = dash_export.availability()
        if st.button("Prepare export files"):
            with st.spinner("Building files..."):
                files, reasons = _build_export_files(spec, filtered, charts, kpis)
            st.session_state.export_files = files
            st.session_state.export_reasons = reasons

        files = st.session_state.get("export_files", {})
        reasons = st.session_state.get("export_reasons", {})
        for key, label_text in EXPORT_LABELS.items():
            ok, reason = available.get(key, (False, "Unavailable."))
            if key in files:
                payload, filename, mime = files[key]
                st.download_button(
                    label_text, payload, file_name=filename, mime=mime, key=f"dl-{key}"
                )
            else:
                detail = reasons.get(key) or (reason if not ok else "Click Prepare export files.")
                st.button(
                    f"{label_text} — {detail}",
                    disabled=True,
                    key=f"disabled-{key}",
                )

    st.caption("Generated by AI from your data. Verify important numbers.")


