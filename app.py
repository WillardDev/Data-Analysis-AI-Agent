@st.cache_data(show_spinner=False)
def _parse_table(raw: bytes, name: str) -> pd.DataFrame:
    if name.lower().endswith((".xlsx", ".xlsm")):
        return pd.read_excel(io.BytesIO(raw), engine="openpyxl")
    return pd.read_csv(io.BytesIO(raw))


def load_table(raw: bytes, name: str) -> pd.DataFrame:
    # The agent's generated code can mutate df (e.g. parsing dates), so never
    # hand out the cached object itself.
    return _parse_table(raw, name).copy()


