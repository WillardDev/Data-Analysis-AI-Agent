def data_summary(df: pd.DataFrame) -> pd.DataFrame:
    return pd.DataFrame(
        {
            "column": df.columns.astype(str),
            "type": [str(t) for t in df.dtypes],
            "missing": df.isna().sum().to_numpy(),
        }
    )


def _looks_like_date(series: pd.Series) -> bool:
    if pd.api.types.is_datetime64_any_dtype(series):
        return True
    name = str(series.name).lower()
    return not pd.api.types.is_numeric_dtype(series) and any(
        key in name for key in ("date", "time", "month", "year", "day")
    )


def _pick_metric(numeric_cols: list[str]) -> str:
    for key in ("revenue", "sales", "amount", "total", "price", "value", "cost"):
        for col in numeric_cols:
            if key in col.lower():
                return col
    return numeric_cols[-1]


def _is_identifier(df: pd.DataFrame, col: str) -> bool:
    """IDs, codes and free-text keys make poor grouping columns."""
    name = str(col).lower()
    if name in {"id", "index", "uuid"} or name.endswith(("_id", "id", "_no", "code")):
        return True
    return df[col].nunique(dropna=True) == len(df) > 20


def suggest_questions(df: pd.DataFrame) -> list[str]:
    """Starter questions derived from the uploaded columns."""
    numeric, categorical, temporal = [], [], []
    for col in df.columns:
        series = df[col]
        if pd.api.types.is_numeric_dtype(series):
            numeric.append(col)
        elif _looks_like_date(series):
            temporal.append(col)
        elif not _is_identifier(df, col):
            categorical.append(col)

    # Prefer business-like dimensions (in priority order), then fewest distinct values.
    preferred = ("product", "item", "category", "region", "segment", "customer", "name", "type")

    def rank(col: str) -> tuple[int, int]:
        name = str(col).lower()
        for index, key in enumerate(preferred):
            if key in name:
                return (index, df[col].nunique(dropna=True))
        return (len(preferred), df[col].nunique(dropna=True))

    categorical.sort(key=rank)

    questions: list[str] = []
    if categorical and numeric:
        metric = _pick_metric(numeric)
        questions.append(f"Which {categorical[0]} has the lowest {metric}?")
        questions.append(f"Which {categorical[0]} has the highest {metric}?")
    if temporal and numeric:
        questions.append(f"Is there a trend in {_pick_metric(numeric)} over time?")
    if numeric:
        questions.append(f"Are there outliers in {_pick_metric(numeric)}?")
    questions.append("Are there missing values I should worry about?")
    return questions[:4]


def _log_size() -> int:
    try:
        return LOG_PATH.stat().st_size
    except OSError:
        return 0


def _read_new_trace(offset: int) -> dict | None:
    """The agent logs one JSON line per completed question; read what was appended."""
    try:
        with LOG_PATH.open("rb") as handle:
            handle.seek(offset)
            chunk = handle.read().decode("utf-8", "ignore")
    except OSError:
        return None
    for line in reversed(chunk.splitlines()):
        line = line.strip()
        if not line:
            continue
        try:
            return json.loads(line)
        except json.JSONDecodeError:
            continue
    return None


def run_agent(question: str, df: pd.DataFrame, history):
    """Call the existing agent, returning its answer plus the trace and charts."""
    offset = _log_size()
    figures_before = len(FIGURES)

    # Work on a copy so a failed call cannot leave a dangling user message in history.
    working = list(history) if history else None

    error: str | None = None
    try:
        answer, new_history = ask(question, df, working)
    except Exception as exc:  # network, auth, rate limit...
        answer, new_history, error = None, history, f"{type(exc).__name__}: {exc}"

    trace = _read_new_trace(offset) or {}
    steps = trace.get("steps", [])
    figures = FIGURES[figures_before:]
    return answer, new_history, steps, figures, error, trace.get("tokens")


def chart_png(fig) -> bytes | None:
    try:
        return fig.to_image(format="png", scale=2)
    except Exception:
        return None


def conversation_markdown() -> str:
    lines = ["# Data Analysis Agent - conversation", ""]
    for entry in st.session_state.chat:
        if entry["role"] == "user":
            lines += ["## You", "", entry["content"], ""]
            continue
        lines += ["## Agent", "", entry["answer"], ""]
        for step in entry.get("steps", []):
            lines += ["```python", step.get("code", ""), "```", ""]
            result = (step.get("result") or "").strip()
            if result:
                lines += ["```text", result[:2000], "```", ""]
    return "\n".join(lines)


def _next_id() -> int:
    st.session_state.entry_seq += 1
    return st.session_state.entry_seq


def render_assistant(entry: dict, show_code: bool) -> None:
    st.markdown(entry["answer"])

    if "png" not in entry:
        entry["png"] = [chart_png(fig) for fig in entry.get("figures", [])]

    for index, fig in enumerate(entry.get("figures", [])):
        st.plotly_chart(fig, width="stretch", key=f"chart-{entry['id']}-{index}")
        png = entry["png"][index] if index < len(entry["png"]) else None
        if png:
            st.download_button(
                "Download chart as PNG",
                png,
                file_name=f"chart-{index + 1}.png",
                mime="image/png",
                key=f"png-{entry['id']}-{index}",
            )
        else:
            st.download_button(
                "Download chart (.html)",
                fig.to_html(include_plotlyjs="cdn"),
                file_name=f"chart-{index + 1}.html",
                mime="text/html",
                key=f"html-{entry['id']}-{index}",
            )

    steps = entry.get("steps") or []
    if not steps and not entry.get("error"):
        return

    with st.expander("How I got this", expanded=show_code):
        if entry.get("error"):
            st.caption("The agent raised an error on this question:")
            st.code(entry["error"], language="text")
        for step in steps:
            flags = "error" if step.get("error") else "ok"
            st.caption(f"{step.get('latency_s', '?')}s · {flags}")
            st.code(step.get("code", ""), language="python")
            result = (step.get("result") or "").strip()
            if result:
                st.text(result[:2000])


